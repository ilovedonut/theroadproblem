import './test-bootstrap.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import { pool } from '../src/db/client.ts';
import { runOfficialIngestion } from '../src/lib/ingestor/official-ingestion.ts';
import { parsePppac,sha256,PPPAC_SOURCE } from '../src/lib/ingestor/adapters/pppac.ts';
const html=fs.readFileSync('tests/fixtures/pppac-karnataka.html');
const base=parsePppac(html.toString()).find(r=>r.package_name.includes('Bangalore-Nidagatta'));
const record={...base,external_key:`${base.external_key}-test-${crypto.randomUUID()}`};
const client=await pool.connect();
const archiveBytes=new Map();
const archive=async(key,body)=>{archiveBytes.set(key,Buffer.from(body));return {key,bucket:'isolated-test-storage',size:body.length,driver:'local'}};
const fetched=(rec,body=html)=>async()=>({body,records:[rec],checksum:sha256(body),contentType:'text/html'});
const invoke=rec=>runOfficialIngestion(client,{fetchSource:fetched(rec),archive,requireRemoteArchive:false});
try {
 const before=(await client.query('SELECT COUNT(*) FROM reports')).rows[0].count;
 const a=await invoke(record);assert.equal(a.new_inserted,1);assert.equal(a.review_required,1);
 assert.ok(archiveBytes.get(a.archive_key).equals(html),'Original evidence bytes preserved');
 const b=await invoke(record);assert.equal(b.unchanged_skipped,1);assert.equal(b.new_inserted,0);
 const changed={...record,approved_project_cost_inr:'20000000000'};
 const c=await invoke(changed);assert.equal(c.updated,1);
 const history=await client.query('SELECT id,checksum_sha256 FROM source_records WHERE external_key=$1',[record.external_key]);assert.equal(history.rows.length,2);
 const works=await client.query(`SELECT w.* FROM works w JOIN source_records sr ON sr.id=w.source_record_id WHERE sr.external_key=$1`,[record.external_key]);assert.equal(works.rows.length,1);
 const work=works.rows[0];assert.equal(work.contract_value_inr,null);assert.equal(work.tender_id,null);assert.equal(work.official_status,'unknown');
 const linked=await client.query('SELECT * FROM work_segments WHERE work_id=$1',[work.id]);assert.equal(linked.rowCount,0,'Uncertain statewide approvals must not receive guessed road pins');
 const d=await invoke(record);assert.equal(d.updated,1,'A publisher reversion must restore the previous projection');
 const e=await invoke(record);assert.equal(e.unchanged_skipped,1);
 assert.equal((await client.query('SELECT COUNT(*) FROM source_records WHERE external_key=$1',[record.external_key])).rows[0].count,'2','Reversions reuse immutable evidence');
 const ev=await client.query('SELECT * FROM events WHERE entity_id=$1 ORDER BY effective_at',[work.id]);assert.equal(ev.rowCount,3);
 await assert.rejects(runOfficialIngestion(client,{fetchSource:fetched({...record,external_key:record.external_key+'-fail'}),archive:async()=>{throw Error('simulated archive failure')}}));
 assert.equal((await client.query('SELECT COUNT(*) FROM source_records WHERE external_key=$1',[record.external_key+'-fail'])).rows[0].count,'0','Archive failure leaves no source facts');
 await assert.rejects(runOfficialIngestion(client,{fetchSource:async()=>{throw Error('simulated network failure')},archive}));
 const ledger=await client.query(`SELECT run_status FROM ingestion_runs WHERE source_name=$1 ORDER BY started_at DESC LIMIT 1`,[PPPAC_SOURCE]);assert.equal(ledger.rows[0].run_status,'failed');
 assert.equal((await client.query('SELECT COUNT(*) FROM reports')).rows[0].count,before);
 let writes=0;
 const dry=await runOfficialIngestion({query(){writes++;throw Error('dry run attempted DB write')}},{dryRun:true,fetchSource:fetched(record),archive});
 assert.equal(writes,0);assert.equal(dry.total_discovered,1);
 console.log('REAL_INGESTION_DATABASE_PASSED');
}finally {client.release();await pool.end();}
